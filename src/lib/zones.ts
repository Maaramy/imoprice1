/**
 * Recherche de zone par gouvernorat (recherche insensible à la casse).
 * Retourne la première zone correspondante, ou null si aucune correspondance.
 */
export function findZoneByGovernorate(governorate: string): ZoneData | null {
  const g = governorate.trim().toLowerCase();
  return ZONE_DATABASE.find(z => z.region.toLowerCase() === g) ?? null;
}

/**
 * Recherche par gouvernorat + ville (uzzy match).
 */
export function findZoneByCity(governorate: string, city: string): ZoneData | null {
  const g = governorate.trim().toLowerCase();
  const c = city.trim().toLowerCase();
  return ZONE_DATABASE.find(z =>
    z.region.toLowerCase() === g && z.city.toLowerCase() === c
  ) ?? findZoneByGovernorate(governorate);
}

/**
 * Recherche par gouvernorat + ville + quartier (uzzy match).
 * Retourne la zone la plus spécifique possible.
 */
export function findZone(governorate?: string | null, city?: string | null, quarter?: string | null): ZoneData | null {
  if (!governorate) return null;
  const g = governorate.trim().toLowerCase();
  const c = city?.trim().toLowerCase() ?? "";
  const q = quarter?.trim().toLowerCase() ?? "";
  if (q) {
    const match = ZONE_DATABASE.find(z =>
      z.region.toLowerCase() === g &&
      z.city.toLowerCase() === c &&
      z.quarter.toLowerCase().includes(q)
    );
    if (match) return match;
  }
  if (c) return findZoneByCity(governorate, city!);
  return findZoneByGovernorate(governorate);
}

